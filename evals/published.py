"""Read the checked-in eval reports so the app can show its own scores.

The reports are generated by ``evals.runner`` and committed under
``evals/reports/``. Surfacing them is display-only, so a malformed report is
logged and skipped rather than allowed to break the listing.
"""

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import List

logger = logging.getLogger(__name__)

REPORTS_DIR = Path(__file__).resolve().parent / "reports"


@dataclass(frozen=True)
class PublishedReport:
    """One eval run, without its per-question detail."""

    name: str
    sut: str
    total: int
    passed: int
    failed: int
    pass_rate: float


def _parse_report(path: Path) -> PublishedReport:
    payload = json.loads(path.read_text())
    return PublishedReport(
        name=path.stem,
        sut=str(payload["sut"]),
        total=int(payload["total"]),
        passed=int(payload["passed"]),
        failed=int(payload["failed"]),
        pass_rate=float(payload["pass_rate"]),
    )


def load_published_reports(reports_dir: Path = REPORTS_DIR) -> List[PublishedReport]:
    """Summarize every readable JSON report in ``reports_dir``, ordered by name."""
    if not reports_dir.is_dir():
        return []

    reports: List[PublishedReport] = []
    for path in sorted(reports_dir.glob("*.json")):
        try:
            reports.append(_parse_report(path))
        except (OSError, ValueError, KeyError, TypeError):
            logger.warning("Skipping unreadable eval report: %s", path.name)
    return reports
